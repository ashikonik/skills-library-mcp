"""Assemble the public repository tree.

The local library is a working directory, not a publishable repo: it holds a
machine scan's worth of generators, personal project paths and absolute home
paths. The public tree is a separate, clean directory containing only what
belongs in a public repository:

  mcp/       the server, its two implementations, tests and docs
  skills/    the skills whose licence permits redistribution
  agents/    the agent definitions whose licence permits redistribution
  ponytail/  the upstream clone, without its .git

Two things are decided by licence, not by taste. An entry is published only
if its own licence permits redistribution -- `provenance.py` resolves that
per entry. And the personal files that leak machine paths are never
published, whatever their licence says.

It is built by copying, so the local working directory is untouched.
"""
