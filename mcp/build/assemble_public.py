def ignore_for(directory, entries):
    """A shutil ignore callback: skip the build artefacts everywhere."""
    return {e for e in entries if e in SKIP_DIRS or e in SCRATCH_FILES}


# The documents that carry a count, and the template each is rendered
# from.
#
# The library and the published tree hold different numbers of entries:
# the tree leaves the private files and the test fixtures out. A number
# written out by hand is therefore wrong in one of them, and it is wrong
# *silently* -- the document still reads fine, it just describes a
# library that is not the one in the directory.
#
# So each of these documents is *rendered* from a template in
# `mcp/docs/templates/`, and the count is filled in from the index. The
# template is the source of truth; the rendered document is a build
# artefact, and is not tracked.
DOC_COUNT_FILES = [
    ('mcp/README.md', 'mcp/docs/templates/README.md.tpl'),
    ('mcp/docs/ARCHITECTURE.md', 'mcp/docs/templates/ARCHITECTURE.md.tpl'),
    ('mcp/docs/REGISTERING.md', 'mcp/docs/templates/REGISTERING.md.tpl'),
    ('mcp/docs/TOOL_REFERENCE.md', 'mcp/docs/templates/TOOL_REFERENCE.md.tpl'),
]


def count_noted_rows(root, index):
    """How many task rows name an entry their own lists omit.

    Read from the *source* table (`mcp/build/tasks.py`), because the
    builder promotes the named entries to the front of the row -- so the
    built index no longer shows which rows had them.

    The *entry names* come from the index, so a row whose note names an
    entry this tree does not publish does not count: in the published
    tree the note's entry is filtered out, and there is nothing left to
    promote.
    """
    table = os.path.join(root, 'mcp', 'build', 'tasks.py')
    if not os.path.isfile(table):
        return 0
    namespace = {}
    try:
        with open(table, encoding='utf-8') as fh:
            exec(compile(fh.read(), table, 'exec'), namespace)
    except Exception as e:                      # noqa: BLE001
        print('  the task table could not be read (%s)' % e)
        return 0
    rows = namespace.get('TASKS') or []
    entry_names = {e.get('name') for e in
                   (index.get('skills') or []) + (index.get('agents') or [])}

    n = 0
    for row in rows:
        if len(row) < 4:
            continue
        _name, skills, agents, note = row[0], row[1], row[2], row[3]
        named = set()
        for raw in BACKTICK.findall(note or ''):
            # an entry name is a bare identifier: no spaces, dots or slashes
            if not re.fullmatch(r'[A-Za-z0-9_-]+', raw):
                continue
            if raw in entry_names:
                named.add(raw)
        own = set(skills or []) | set(agents or [])
        if named - own:
            n += 1
    return n


def doc_counts(root):
    """The counts the documentation states, read from the index.

    Every number the documentation quotes is filled in from here, so a
    number cannot drift away from the library it describes. The
    documents used to carry their own copies of these figures, and
    they went stale -- the task-table row count, the tier counts, the
    vocabulary size and the ranking figures all drifted as the library
    changed, and nobody noticed because the numbers were prose.

    The ranking figures are not in the index: they are the result of
    running the search over the labelled query set. So they are
    *measured* here, against this tree's own index, rather than copied
    from a previous run.
    """
    index_path = os.path.join(root, 'mcp', 'data', 'index.json')
    if not os.path.isfile(index_path):
        return None
    with open(index_path, encoding='utf-8') as fh:
        index = json.load(fh)

    n_skills = len(index.get('skills') or [])
    n_agents = len(index.get('agents') or [])
    n_total = n_skills + n_agents
    by_tier = (index.get('counts') or {}).get('by_tier') or {}
    n_tier1 = by_tier.get('1', by_tier.get(1, 0))
    n_tier2 = by_tier.get('2', by_tier.get(2, 0))
    n_tier3 = by_tier.get('3', by_tier.get(3, 0))

    # The tier counts for skills alone. Tiers 2 and 3 hold no agents, so
    # the two sets agree there; tier 1 does not, and the tier table in
    # the architecture guide is about skills.
    skill_by_tier = (index.get('counts') or {}).get('skill_by_tier') or by_tier
    n_skill_tier1 = skill_by_tier.get('1', skill_by_tier.get(1, 0))
    n_skill_tier2 = skill_by_tier.get('2', skill_by_tier.get(2, 0))
    n_skill_tier3 = skill_by_tier.get('3', skill_by_tier.get(3, 0))
    n_tasks = len(index.get('tasks') or [])
    n_domains = len(index.get('domains') or {})

    # The rows whose *note* names an entry their own lists omit.
    #
    # This is a fact about the *source* task table, not about the index:
    # the builder promotes the named entries to the front of the row, so
    # by the time a row reaches the index there is nothing left to
    # detect. It is read from the table instead.
    #
    # The documentation used to say "Nine of the 73 rows", and the table
    # had been edited since -- so the number was already wrong before
    # this was computed. Now it cannot be wrong again.
    n_noted_rows = count_noted_rows(root, index)

    # The vocabulary: every token the corpus's name and description
    # fields produce. This is the set the cross-implementation gate
    # pushes through both tokenizers, so it is the number the gate
    # actually covers.
    vocab = set()
    for e in (index.get('skills') or []) + (index.get('agents') or []):
        tokens = e.get('tokens') or {}
        vocab.update(tokens.get('name') or [])
        vocab.update(tokens.get('desc') or [])

    subs = {
        '{n_skills}': str(n_skills),
        '{n_agents}': str(n_agents),
        '{n_total}': '{:,}'.format(n_total),
        '{n_tier1}': str(n_tier1),
        '{n_tier2}': str(n_tier2),
        '{n_tier3}': str(n_tier3),
        '{n_skill_tier1}': str(n_skill_tier1),
        '{n_skill_tier2}': str(n_skill_tier2),
        '{n_skill_tier3}': str(n_skill_tier3),
        '{n_tasks}': str(n_tasks),
        '{n_domains}': str(n_domains),
        '{n_vocab}': '{:,}'.format(len(vocab)),
        '{n_noted_rows}': str(n_noted_rows),
    }

    # The ranking figures, measured against this tree's own index.
    #
    # A failure here is not fatal to the build: the measurement is
    # also a gate in its own right, and it reports its own failures.
    # Here, a failure just means the documents cannot quote a ranking
    # figure, so the tokens are left unfilled rather than filled with
    # a stale one.
    try:
        m = measure_ranking(index)
    except Exception as e:                      # noqa: BLE001
        print('  the ranking figures could not be measured (%s); the '
              'documents will not quote them' % e)
        return subs
    subs.update({
        '{eval_rank1}': '%d / %d' % (m['top1'], m['measured']),
        '{eval_top3}': '%d / %d' % (m['top3'], m['measured']),
        '{eval_top10}': '%d / %d' % (m['top10'], m['measured']),
        '{n_queries}': str(m['measured']),
    })
    return subs


def fill_doc_counts(root):
    """Render the documentation from its templates, with the counts.

    Called for the public tree with the tree's own counts, and for the
    local library with the local counts -- so neither document ever
    describes a library other than the one it sits in.
    """
    subs = doc_counts(root)
    if subs is None:
        return

    changed = 0
    for rel, tpl_rel in DOC_COUNT_FILES:
        tpl = os.path.join(root, tpl_rel)
        if not os.path.isfile(tpl):
            continue
        with open(tpl, encoding='utf-8') as fh:
            text = fh.read()
        for token, value in subs.items():
            text = text.replace(token, value)
        out = os.path.join(root, rel)
        os.makedirs(os.path.dirname(out), exist_ok=True)
        with open(out, 'w', encoding='utf-8') as fh:
            fh.write(text)
        changed += 1
    print('rendered %d document(s) with the counts' % changed)


def copy_tree(src_rel, dst_rel, skip_extra=()):
    src = os.path.join(SRC, src_rel)
    dst = os.path.join(DST, dst_rel)
    if os.path.exists(dst):
        shutil.rmtree(dst)
    os.makedirs(os.path.dirname(dst), exist_ok=True)
    shutil.copytree(src, dst, symlinks=False, ignore=ignore_for)
    for entry in set(skip_extra) | SKIP_DIRS:
        p = os.path.join(dst, entry)
        if os.path.isdir(p):
            shutil.rmtree(p)
        elif os.path.exists(p):
            os.remove(p)
    return dst


def count_files(path):
    return sum(len(f) for _, _, f in os.walk(path))


def clear_tree(path):
    """Empty a directory, keeping its `.git`.

    The public tree becomes the repository once it is pushed, and the
    assembler is run again after that -- a new licence decision, a new
    upstream, a typo fix. Wiping `.git` with everything else would
    throw away the history and the remote.

    Everything *else* is removed, including files the assembler no
    longer produces. A stale file left behind is a file nobody
    accounted for, and the whole point of this tree is that every file
    in it is either published content or the server's own source.
    """
    for name in os.listdir(path):
        if name == '.git':
            continue
        p = os.path.join(path, name)
        if os.path.isdir(p) and not os.path.islink(p):
            shutil.rmtree(p)
        else:
            os.remove(p)


def copy_skill(entry, kind):
    """Copy one skill directory or one agent file.

    The library path is `skills/<name>/` for a skill and `agents/<name>.md`
    for an agent; the source path is where the content actually came from,
    and it may differ (a skill promoted into `skills/` from a plugin cache).
    """
    rel = entry['path'].rstrip('/')
    src = os.path.join(SRC, rel)
    dst = os.path.join(DST, rel)
    if os.path.exists(dst):
        return False
    os.makedirs(os.path.dirname(dst), exist_ok=True)
    if os.path.isdir(src):
        shutil.copytree(src, dst, symlinks=False, ignore=ignore_for)
    else:
        shutil.copy2(src, dst)
    return True


def redact_manifest(path):
    """Strip the absolute library root from a run manifest.

    The tracked copy of the manifest is a record of a run *on this
    machine*. The absolute root it names is useless to a reader and
    names the machine, so it is removed. The unredacted manifest stays
    in `logs/`, which is not tracked.
    """
    if not os.path.isfile(path):
        return
    try:
        with open(path, encoding='utf-8') as fh:
            data = json.load(fh)
    except (OSError, ValueError):
        return
    if not isinstance(data, dict) or 'library_root' not in data:
        return
    data.pop('library_root', None)
    with open(path, 'w', encoding='utf-8') as fh:
        json.dump(data, fh, indent=2, sort_keys=True)
        fh.write('\n')
    print('  redacted %s' % os.path.relpath(path, DST))


def public_provenance(provenance):
    """The provenance table, with the machine's paths removed.

    The local table records `source` -- the absolute path the content
    was found at -- because that is what makes the resolution auditable
    locally. In a public tree that path is both useless (it names the
    machine that built it, not the upstream the content came from) and
    a leak (it exposes a username and a directory layout).

    The container label already answers the same question in a portable
    way: `plugin:zotero`, `marketplace:claude-plugins-official`,
    `ecc`, `this-library`. The upstream repository and the owner are
    recorded beside it, so nothing is lost that a reader could have
    used.
    """
    out = []
    for e in provenance:
        e = dict(e)
        e['source'] = e.get('container') or ''
        out.append(e)
    return out


def write_public_data(provenance, drop):
    """Write the public `.library_data.json`.

    Two changes from the local one:

    * it holds only the published entries, so the count matches the tree;
    * `source` becomes a container label rather than an absolute path, so
      the file names no one's home directory. The upstream is recorded in
      `mcp/data/provenance.json` and in `CREDITS.md`.
    """
    published = {e['path'].rstrip('/') for e in provenance
                 if e['verdict'] in ('redistributable', 'included-with-terms')}
    container_of = {e['path'].rstrip('/'): e['container']
                    for e in provenance
                    if e['verdict'] in ('redistributable', 'included-with-terms')}

    with open(os.path.join(SRC, '.library_data.json'), encoding='utf-8') as fh:
        local = json.load(fh)

    out = {}
    for key in ('skills', 'agents'):
        rows = []
        for r in local.get(key) or []:
            rel = r['path'].rstrip('/')
            if rel not in published:
                continue
            r = dict(r)
            r['source'] = container_of.get(rel) or ''
            rows.append(r)
        out[key] = rows

    out['excluded_agents'] = [
        dict(r, source=container_of.get(r['path'].rstrip('/'), ''))
        for r in (local.get('excluded_agents') or [])
        if r['path'].rstrip('/') in published
    ]

    path = os.path.join(DST, '.library_data.json')
    with open(path, 'w', encoding='utf-8') as fh:
        json.dump(out, fh, indent=1, sort_keys=True, ensure_ascii=False)
        fh.write('\n')
    print('wrote .library_data.json  (%d skills, %d agents, %d held aside)' % (
        len(out['skills']), len(out['agents']), len(out['excluded_agents'])))


def read_held_aside_readme():
    """The local held-aside agents' README, parsed into its rows.

    The table answers three questions per agent -- who dispatches it,
    why it is not standalone, and where it came from. The first two are
    the maintainer's own notes and must be carried across; the third is
    an absolute path and must not be.
    """
    path = os.path.join(SRC, 'agents', '_agent-specific', 'README.md')
    if not os.path.isfile(path):
        return {}
    rows = {}
    with open(path, encoding='utf-8') as fh:
        for line in fh:
            line = line.strip()
            if not line.startswith('|'):
                continue
            cells = [c.strip() for c in line.strip('|').split('|')]
            if len(cells) != 4:
                continue
            name = cells[0].strip('`')
            if not name or name in ('Agent', '---'):
                continue
            rows[name] = cells
    return rows


def write_held_aside_readme(provenance):
    """Write the public tree's held-aside agents' README.

    Two differences from the local one:

    * only the *published* agents are listed -- the licence filter
      removed eight of the fourteen, and a README that described files
      that are not here would be a lie;
    * the "Original source" column holds the container label rather
      than the absolute path, so the file identifies the upstream
      without naming the machine the content was found on.
    """
    path = os.path.join(DST, 'agents', '_agent-specific', 'README.md')
    if not os.path.isdir(os.path.dirname(path)):
        return

    local_rows = read_held_aside_readme()
    published = [e for e in provenance
                 if e.get('held_aside')
                 and e['verdict'] in ('redistributable', 'included-with-terms')]
    if not published:
        return

    L = []
    w = L.append
    w('# Pipeline-internal agents — not for direct invocation')
    w('')
    w('These %d definitions are **dispatch targets**, not standalone tools.'
      % len(published))
    w('Each one is invoked by an orchestrating agent as part of a larger')
    w('workflow. Invoking one directly will fail or produce nonsense,')
    w('because they expect parameters (a scan root, a workspace clone, a')
    w('comparison result path) that only the parent workflow supplies.')
    w('')
    w('They are kept here rather than deleted so the pipelines remain')
    w('reproducible.')
    w('')
    w('| Agent | Dispatched by | Why it is not standalone | Original source |')
    w('|---|---|---|---|')
    for e in published:
        cells = local_rows.get(e['name'])
        dispatched = cells[1] if cells else '—'
        why = cells[2] if cells else '—'
        w('| `%s` | %s | %s | %s |'
          % (e['name'], dispatched, why, e.get('container') or '—'))
    w('')
    w('The "Original source" column names the *container* the agent came')
    w('from — the plugin, the marketplace or the project — rather than a')
    w('path on the machine that assembled this tree. The full attribution')
    w('for every entry is in `mcp/data/provenance.json` and `CREDITS.md`.')
    w('')

    with open(path, 'w', encoding='utf-8') as fh:
        fh.write('\n'.join(L) + '\n')
    print('  wrote %s (%d published agents)'
          % (os.path.relpath(path, DST), len(published)))


def regenerate_golden():
    """Rewrite the public tree's golden search file for its OWN corpus.

    The golden file records what the search engine returns for a fixed
    set of queries, so it is a property of the corpus as much as of the
    engine. The public tree holds fewer skills than the local one --
    the licence filter removes entries -- so the local golden file
    does not describe it, and copying it across would make the
    agreement test report drift that is not drift at all.

    The file is regenerated by the same code that writes it normally,
    so it is not "whatever the engine does right now": the engine is
    unchanged between the two trees, and the difference is the corpus.
    """
    import shutil
    dst_golden = os.path.join(DST, 'mcp', 'tests', 'golden')
    if os.path.isdir(dst_golden):
        shutil.rmtree(dst_golden)
    os.makedirs(dst_golden, exist_ok=True)

    env = dict(os.environ)
    r = subprocess.run(
        [sys.executable, os.path.join(DST, 'mcp', 'tests', 'test_agreement.py'),
         '--update-golden'],
        capture_output=True, text=True, env=env, cwd=DST)
    path = os.path.join(dst_golden, 'search_golden.json')
    if r.returncode != 0 or not os.path.isfile(path):
        print('  WARNING: could not regenerate the golden file')
        sys.stderr.write(r.stdout[-2000:])
        sys.stderr.write(r.stderr[-2000:])
        return
    print('regenerated the golden file for this tree (%d bytes)'
          % os.path.getsize(path))


def main():
    provenance = resolve()
    # Two verdicts publish. `redistributable` is published on the
    # strength of its own licence. `included-with-terms` is published
    # because the repository's owner instructed it, and its upstream
    # terms do not grant redistribution -- the NOTICE says so, and
    # quotes the terms, so the position is on the record rather than
    # implied.
    keep = [e for e in provenance
            if e['verdict'] in ('redistributable', 'included-with-terms')]
    drop = [e for e in provenance
            if e['verdict'] not in ('redistributable', 'included-with-terms')]

    n_plain = sum(1 for e in keep if e['verdict'] == 'redistributable')
    n_terms = sum(1 for e in keep if e['verdict'] == 'included-with-terms')

    print('provenance: %d entries' % len(provenance))
    print('  publishing %d (licence permits redistribution)' % n_plain)
    print('  publishing %d (owner\'s instruction; terms do not grant it)'
          % n_terms)
    print('  excluding %d (licence or personal)' % len(drop))

    if os.path.exists(DST):
        print('removing the previous public tree: %s' % DST)
        clear_tree(DST)
    os.makedirs(DST, exist_ok=True)

    # --- the server and its tooling
    for src_rel, skip_extra in COPY_DIRS:
        if src_rel in ('skills', 'agents'):
            continue        # copied entry by entry below, filtered by licence
        dst = copy_tree(src_rel, src_rel, skip_extra)
        print('copied %-14s %5d files' % (src_rel, count_files(dst)))

    for f in COPY_FILES:
        s = os.path.join(SRC, f)
        if os.path.isfile(s):
            shutil.copy2(s, os.path.join(DST, f))
    print('copied %-14s %5d files' % ('root files', len(COPY_FILES)))

    # --- the tracked run manifest. It is a record of a run on the
    #     builder's machine, so the absolute library root has to go
    #     before it is copied: the manifest in `logs/` keeps it, and
    #     the tracked copy is for readers.
    redact_manifest(os.path.join(DST, 'mcp', 'docs', 'last-run.json'))

    # --- the public tree's own .gitignore. Not the local one: locally
    #     `skills/` and `agents/` are regenerated by a machine scan and
    #     are ignored, but here they ARE the content.
    with open(os.path.join(DST, '.gitignore'), 'w', encoding='utf-8') as fh:
        fh.write(PUBLIC_GITIGNORE)
    print('wrote %-14s %5d bytes' % ('.gitignore', len(PUBLIC_GITIGNORE)))

    # --- the published skills and agents, entry by entry, so that the
    #     licence filter actually applies: the tree copy above would have
    #     brought every entry along, including the ones that must not be
    #     published.
    n_skill = n_agent = n_held = 0
    for e in keep:
        if copy_skill(e, e['kind']):
            if e.get('held_aside'):
                n_held += 1
            elif e['kind'] == 'skill':
                n_skill += 1
            else:
                n_agent += 1
    print('copied %-14s %5d skills' % ('skills/', n_skill))
    print('copied %-14s %5d agents' % ('agents/', n_agent))
    print('copied %-14s %5d held-aside agents' % ('agents/_agent-specific', n_held))

    # --- the library data, filtered and de-pathed.
    #     `source` records where the content came from on the machine that
    #     assembled it. That is provenance -- it belongs in the public tree,
    #     but as a *container* label, not as an absolute path that names
    #     somebody's home directory. The upstream is recorded in the
    #     provenance table and in CREDITS.md instead.
    write_public_data(provenance, drop)

    # --- the held-aside agents' README. Rebuilt for the published
    #     subset, with the container label instead of the machine path.
    write_held_aside_readme(provenance)

    # --- the upstream clone, minus its .git
    for clone in UPSTREAM_CLONES:
        dst = copy_tree(clone, clone)
        nested = os.path.join(dst, '.git')
        if os.path.isdir(nested):
            shutil.rmtree(nested)
            print('removed %s/.git' % clone)
        print('copied %-14s %5d files' % (clone, count_files(dst)))

    # --- the README. Generated, because its counts are properties of
    #     the tree, and different from the local library's README: this
    #     one describes a public repository.
    r = subprocess.run([sys.executable,
                        os.path.join(HERE, 'public_readme.py')],
                       capture_output=True, text=True)
    if r.returncode != 0:
        print('  WARNING: the README could not be written')
        sys.stderr.write(r.stderr[-2000:])
    else:
        print(r.stdout.strip())

    # --- the provenance table, so the tree can be audited on its own.
    #     De-pathed: the `source` becomes the container label, so the
    #     table records where the content came from without recording
    #     whose machine it was found on.
    pub_prov = public_provenance(provenance)
    prov_dst = os.path.join(DST, 'mcp', 'data', 'provenance.json')
    os.makedirs(os.path.dirname(prov_dst), exist_ok=True)
    with open(prov_dst, 'w', encoding='utf-8') as fh:
        json.dump(pub_prov, fh, indent=2, sort_keys=True, ensure_ascii=False)
        fh.write('\n')

    print()
    total = subprocess.run(['du', '-sh', DST], capture_output=True,
                           text=True).stdout.strip()
    print('public tree: %s' % total)
    print('  at %s' % DST)

    # --- the excluded list, for the NOTICE. De-pathed for the same
    #     reason: it names the entries that were left out, and a public
    #     tree must not name the machine they came from.
    ex = os.path.join(DST, 'mcp', 'data', 'excluded.json')
    with open(ex, 'w', encoding='utf-8') as fh:
        json.dump(public_provenance(drop), fh, indent=2, sort_keys=True,
                  ensure_ascii=False)
        fh.write('\n')
    print('  excluded list -> %s' % os.path.relpath(ex, DST))

    # --- the NOTICE, before the gate. The gate below checks that every
    #     entry published under terms that do not grant redistribution
    #     is *named* in the NOTICE -- so the NOTICE has to exist by the
    #     time the gate runs. It is written here from the same
    #     provenance table that decided what shipped, so it cannot
    #     describe a different set of entries than the tree holds.
    #
    #     All three are written here, from the same provenance table that
    #     decided what shipped, so they cannot describe a different set of
    #     entries than the tree holds. `LICENSE` and `CREDITS.md` are
    #     written too -- the NOTICE names them, and a NOTICE that points
    #     at a file the tree does not carry is a broken promise.
    from write_credits import write_credits, write_license, write_notice
    write_license(os.path.join(DST, 'LICENSE'))
    write_notice(os.path.join(DST, 'NOTICE'), pub_prov)
    write_credits(os.path.join(DST, 'CREDITS.md'), pub_prov)
    print('  wrote LICENSE, NOTICE, CREDITS.md')

    # --- the index, then the golden file, which describes this tree's
    #     own results. The order matters: the golden file is produced
    #     by running the search over the index.
    print()
    r = subprocess.run([sys.executable, os.path.join(DST, 'mcp', 'build', 'build_index.py')],
                       capture_output=True, text=True, cwd=DST)
    if r.returncode != 0:
        print('  WARNING: the index build failed')
        sys.stderr.write(r.stdout[-2000:])
        sys.stderr.write(r.stderr[-2000:])
    else:
        print(r.stdout.strip())
    regenerate_golden()

    # --- the documentation, rendered from its templates with this
    #     tree's own counts. It happens here, after the index build,
    #     because the index is what the counts are read from. The
    #     library and the published tree hold different numbers of
    #     entries -- the tree leaves the private files and the test
    #     fixtures out -- so a number written out by hand is wrong in
    #     one of them, silently.
    fill_doc_counts(DST)

    # --- the licence gate. The whole point of this tree is that an
    #     entry is published only if its licence permits redistribution,
    #     so that claim is checked against the filesystem rather than
    #     against the assembler's own bookkeeping.
    #
    #     A copy step that went wrong once would ship content whose
    #     licence forbids it, and the count in the index would still
    #     look right -- the index is built from the provenance table,
    #     not from the disk.
    verify_licence_filter(keep, drop)
    verify_no_leaks()


def verify_no_leaks():
    """The tree must not name the machine that built it.

    The licence gate proves the tree holds the right *entries*. This one
    proves it holds the right *bytes*: an absolute home path anywhere in
    the tree is both a privacy leak and a wrong instruction, because
    every reader of the repository has a different home directory.

    Third-party example paths -- `/home/alice/`, `/Users/benlesh/` -- are
    left alone. They are the upstream authors' own examples, and they
    are correct there. The scanner only flags the builder's home.
    """
    r = subprocess.run([sys.executable,
                        os.path.join(HERE, 'scan_leaks.py'), DST],
                       capture_output=True, text=True)
    print()
    sys.stdout.write(r.stdout)
    if r.stderr.strip():
        sys.stderr.write(r.stderr)
    if r.returncode != 0:
        print('LEAK GATE: FAILED')
        sys.exit(1)
    print('LEAK GATE: PASS')


def verify_licence_filter(keep, drop):
    """Every excluded entry must be absent from the tree, and every
    published one present.

    This is the check that makes the licence filter trustworthy. It
    compares the *filesystem* against the verdicts -- not the index,
    which is derived from the same table the filter used and would
    agree with it by construction.
    """
    published = {e['path'].rstrip('/') for e in keep}
    excluded = {e['path'].rstrip('/') for e in drop
                if e.get('path') and not e.get('held_aside')}

    on_disk = set()
    for name in os.listdir(os.path.join(DST, 'skills')):
        p = os.path.join(DST, 'skills', name)
        if os.path.isdir(p):
            on_disk.add('skills/' + name)
    # The agents are files, in their own directory. They are checked
    # here too: an agent whose licence forbids redistribution must not
    # be in the tree either.
    agents_dir = os.path.join(DST, 'agents')
    if os.path.isdir(agents_dir):
        for name in os.listdir(agents_dir):
            p = os.path.join(agents_dir, name)
            if os.path.isfile(p) and name.endswith('.md'):
                on_disk.add('agents/' + name)
            elif os.path.isdir(p):
                for f in os.listdir(p):
                    if f.endswith('.md'):
                        on_disk.add('agents/%s/%s' % (name, f))

    leaked = sorted(excluded & on_disk)
    missing = sorted(published - on_disk)

    print()
    if leaked:
        print('LICENCE GATE: FAILED')
        print('  %d excluded entries are present in the tree:' % len(leaked))
        for p in leaked[:20]:
            print('    %s' % p)
        sys.exit(1)
    if missing:
        print('LICENCE GATE: FAILED')
        print('  %d published entries are missing from the tree:' % len(missing))
        for p in missing[:20]:
            print('    %s' % p)
        sys.exit(1)
    print('LICENCE GATE: PASS')
    print('  %d published entries are present' % len(published))
    print('  %d excluded entries are absent' % len(excluded))

    # The entries published under terms that do not grant redistribution
    # have to be *named* in the NOTICE, or the tree would ship material
    # whose terms forbid it without saying so. This asserts the record
    # exists, entry by entry.
    terms = [e for e in keep if e['verdict'] == 'included-with-terms']
    if terms:
        notice = os.path.join(DST, 'NOTICE')
        if not os.path.isfile(notice):
            print('LICENCE GATE: FAILED')
            print('  NOTICE is missing, so the terms are not on the record')
            sys.exit(1)
        with open(notice, encoding='utf-8') as fh:
            notice_text = fh.read()
        unnamed = sorted(e['name'] for e in terms
                          if ('`%s`' % e['name']) not in notice_text)
        if unnamed:
            print('LICENCE GATE: FAILED')
            print('  %d entries published under terms are not named in the '
                  'NOTICE:' % len(unnamed))
            for n in unnamed[:20]:
                print('    %s' % n)
            sys.exit(1)
        print('  %d entries published under terms are named in the NOTICE'
              % len(terms))

    # The NOTICE points at `LICENSE` and `CREDITS.md`. If either is
    # absent, the tree ships content whose terms it has not recorded --
    # and the NOTICE's own promise to name the file is broken.
    for required in ('LICENSE', 'NOTICE', 'CREDITS.md'):
        if not os.path.isfile(os.path.join(DST, required)):
            print('LICENCE GATE: FAILED')
            print('  %s is missing from the tree' % required)
            sys.exit(1)

    # The credits are the attribution. Every published entry has to be
    # in there, or the tree ships work without saying who wrote it --
    # which is the whole thing the user asked for when they instructed
    # that the terms-restricted entries be included.
    credits = os.path.join(DST, 'CREDITS.md')
    with open(credits, encoding='utf-8') as fh:
        credits_text = fh.read()
    uncredited = sorted(e['name'] for e in keep
                        if ('`%s`' % e['name']) not in credits_text)
    if uncredited:
        print('LICENCE GATE: FAILED')
        print('  %d published entries are not credited in CREDITS.md:'
              % len(uncredited))
        for n in uncredited[:20]:
            print('    %s' % n)
        sys.exit(1)
    print('  all %d published entries are credited in CREDITS.md' % len(keep))


if __name__ == '__main__':
    main()
