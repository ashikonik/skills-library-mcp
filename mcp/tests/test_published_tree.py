#!/usr/bin/env python3
"""The published tree must be a copy of this one, not a fork of it.

`mcp/build/assemble_public.py` assembles `../skills-library-mcp-public`
by copying this tree's server and tooling into it. It *clears* the
destination first, so the published tree can never hold a hand-made
edit: the next assembly silently discards it.

That is a good property for a build artefact and a bad one for a
collaborator. Someone who opens the published tree -- because that is
the one on GitHub, and the one the README points at -- edits the wrong
file and loses the work with no error and no warning.

This test makes the loss loud instead of silent. It compares the two
trees file by file and names every file that has drifted.

What is compared: the files the assembler copies -- `mcp/` (minus the
build artefacts), the skills, the agents, and the root files it
carries across. What is *not* compared: the generated artefacts
(`mcp/data/index.json`, the rendered documents, `__pycache__`), which
are produced separately in each tree, and `skills/`/`agents/` in the
upstream, which are a machine scan rather than published content.

When the published tree does not exist -- a fresh clone of the upstream
alone -- the test skips, naming the fact. It does not report a pass.
"""
import filecmp
import os
import subprocess
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
MCP = os.path.dirname(HERE)
BASE = os.path.dirname(MCP)

PUBLIC = os.environ.get('PUBLIC_TREE') or os.path.join(
    os.path.dirname(BASE), 'skills-library-mcp-public')

# Files that are produced rather than copied, and so are expected to
# differ between the two trees.
GENERATED = {
    'mcp/data/index.json',
    'mcp/data/provenance.json',
    'mcp/data/excluded.json',
    'mcp/data/cases.json',
    'mcp/README.md',
    'mcp/docs/ARCHITECTURE.md',
    'mcp/docs/INSTALLING.md',
    'mcp/docs/REGISTERING.md',
    'mcp/docs/TOOL_REFERENCE.md',
    'mcp/docs/last-run.json',
    # Regenerated in the published tree against its own corpus: the
    # licence filter removes entries there, so the upstream's golden
    # file does not describe it. `assemble_public.py:450-470` writes it
    # from the tree it is assembling into.
    'mcp/tests/golden/search_golden.json',
}

# Directories that hold a build artefact or a cache in one tree or the
# other.
SKIP_DIRS = {'node_modules', 'dist', '__pycache__', '.git'}

# The upstream's `skills/` and `agents/` are regenerated by a machine
# scan and are not published content -- the published tree holds a
# licence-filtered copy of them under the same paths. They are
# compared separately, by name only, because their contents differ by
# design (the licence filter).
LICENCE_FILTERED = {'skills', 'agents'}


def tracked_source_files(root):
    """Every source file in `root/mcp`, relative to `root`.

    The list comes from git, not from the filesystem, so a file that is
    ignored upstream -- a build artefact -- is not compared, and a file
    that is tracked is compared even when it is absent from disk (a
    deleted-but-not-committed file is a real difference).
    """
    try:
        out = subprocess.run(
            ['git', '-C', root, 'ls-files', 'mcp'],
            capture_output=True, text=True, check=True).stdout
    except (subprocess.CalledProcessError, FileNotFoundError):
        return None
    files = []
    for line in out.splitlines():
        rel = line.strip()
        if not rel or rel in GENERATED:
            continue
        if any(part in SKIP_DIRS for part in rel.split('/')):
            continue
        files.append(rel)
    return sorted(files)


def compare(a_root, b_root, files):
    """The files in `files` that differ between the two roots."""
    differing = []
    for rel in files:
        a = os.path.join(a_root, rel)
        b = os.path.join(b_root, rel)
        if not os.path.exists(a):
            differing.append((rel, 'missing from this tree'))
            continue
        if not os.path.exists(b):
            differing.append((rel, 'missing from the published tree'))
            continue
        if os.path.isdir(a) or os.path.isdir(b):
            continue
        if not filecmp.cmp(a, b, shallow=False):
            differing.append((rel, 'contents differ'))
    return differing


def main():
    if not os.path.isdir(PUBLIC):
        print('SKIP: no published tree at %s' % PUBLIC)
        print('      This tree is not the upstream. The published tree is')
        print('      assembled from it by mcp/build/assemble_public.py.')
        return 0

    if not os.path.isdir(os.path.join(PUBLIC, '.git')):
        print('SKIP: %s is not a git repository.' % PUBLIC)
        return 0

    files = tracked_source_files(BASE)
    if files is None:
        print('SKIP: this tree is not a git repository, so its tracked')
        print('      files cannot be enumerated.')
        return 0

    print('comparing %d tracked source files against the published tree'
          % len(files))

    differing = compare(BASE, PUBLIC, files)
    if differing:
        for rel, why in differing:
            sys.stderr.write('FAIL: %s -- %s\n' % (rel, why))
        sys.stderr.write(
            '\n%d file(s) differ. The published tree is assembled from\n'
            'this one by mcp/build/assemble_public.py, which CLEARS the\n'
            'destination before copying -- so a hand-made edit there is\n'
            'lost the next time the assembler runs, with no error.\n'
            '\nMake the change HERE, in %s, then run:\n'
            '    python3 mcp/build/assemble_public.py\n'
            % (len(differing), BASE))
        return 1

    print('ok   every tracked source file is byte-identical')

    # The published tree tracks the skills and the agents -- they are
    # the repository. The upstream's copies are a machine scan, filtered
    # by licence on the way out, so the two sets differ by design. What
    # must hold is that the published tree has them at all.
    for name in sorted(LICENCE_FILTERED):
        pub = os.path.join(PUBLIC, name)
        if not os.path.isdir(pub):
            sys.stderr.write('FAIL: the published tree has no %s/ directory\n' % name)
            return 1
        count = sum(len(files) for _, _, files in os.walk(pub))
        print('ok   the published tree carries %s/ (%d files)' % (name, count))

    return 0


if __name__ == '__main__':
    sys.exit(main())
