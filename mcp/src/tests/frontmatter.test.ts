// --------------------------------------------------------- AGENTS.md
test('an AGENTS.md section is plain markdown with a marker', () => {
  const section = emitAgentsmdSection('tdd-workflow', 'Write the test first.');
  assert.ok(section.startsWith(agentsmdMarker('tdd-workflow')));
  assert.ok(section.includes('## tdd-workflow'));
  assert.ok(section.includes('Write the test first.'));
  // No frontmatter -- an AGENTS.md is a document, not a skill file.
  assert.ok(!section.includes('---'));
});

test('an AGENTS.md section can be replaced without touching the others', () => {
  const a = emitAgentsmdSection('alpha', 'desc of alpha');
  const b = emitAgentsmdSection('beta', 'desc of beta');
  const file = a + b;

  const replaced = replaceSection(file, agentsmdMarker('alpha'),
    emitAgentsmdSection('alpha', 'NEW desc'));

  assert.ok(replaced.includes('NEW desc'));
  assert.ok(replaced.includes('desc of beta'));
  assert.equal((replaced.match(/skills-library:alpha/g) || []).length, 1);
  assert.equal((replaced.match(/skills-library:beta/g) || []).length, 1);
});
