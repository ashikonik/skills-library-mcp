// ------------------------------------------------------------- the reader
test('normTools handles the three shapes in the library', () => {
  assert.deepEqual(normTools(['Read', 'Grep']), ['Read', 'Grep']);
  assert.deepEqual(normTools('Read, Grep'), ['Read', 'Grep']);
  assert.deepEqual(normTools('Read Grep'), ['Read', 'Grep']);
  assert.deepEqual(normTools('["Read", "Grep"]'), ['Read', 'Grep']);
  assert.deepEqual(normTools(null), []);
});

test('the regex reader recovers an inline list and a quoted scalar', () => {
  const raw = "name: Explore\ntools: ['search', 'read']\nmodel: 'opus'";
  assert.deepEqual(regexFieldRaw(raw, 'tools'), ['search', 'read']);
  assert.equal(regexFieldRaw(raw, 'model'), 'opus');
  assert.equal(regexFieldRaw(raw, 'name'), 'Explore');
});

test('the reader falls back rather than throwing on invalid YAML', () => {
  // An unquoted ':' inside a plain scalar is not valid YAML. The reader
  // must still return its fields rather than throwing.
  //
  // The fixture is written to a temporary file rather than read from
  // the library: the two agents whose frontmatter PyYAML rejects are
  // excluded from the public tree by their licence, so a test that
  // read one of them would fail there for a reason that has nothing
  // to do with the reader.
  const p = join(tmpdir(), 'skills-lib-frontmatter-fixture.md');
  writeFileSync(
    p,
    [
      '---',
      'name: Explore',
      'description: Use this agent when exploring: it looks around.',
      "tools: ['search', 'read', 'web']",
      'model: opus',
      '---',
      '',
      'Body text.',
    ].join('\n'),
    'utf-8',
  );
  try {
    const fm = parseFrontmatter(p);
    assert.equal(fm.parse_ok, false);
    assert.ok(fm.parse_error, 'a parse error must be recorded');
    assert.ok(fm.raw, 'the raw frontmatter must be kept');
    assert.deepEqual(
      normTools(regexFieldRaw(fm.raw, 'tools')),
      ['search', 'read', 'web'],
    );
    assert.equal(regexFieldRaw(fm.raw, 'name'), 'Explore');
  } finally {
    rmSync(p, { force: true });
  }
});

test('the reader parses valid YAML', () => {
  const p = join(tmpdir(), 'skills-lib-frontmatter-valid.md');
  writeFileSync(
    p,
    ['---', 'name: code-reviewer', 'description: Reviews code.', '---', '', 'Body.'].join('\n'),
    'utf-8',
  );
  try {
    const fm = parseFrontmatter(p);
    assert.equal(fm.parse_ok, true);
    assert.ok(fm.data['name']);
  } finally {
    rmSync(p, { force: true });
  }
});

